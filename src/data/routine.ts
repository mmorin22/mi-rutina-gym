export const ALL_EXERCISES: ExerciseDefinition[] = ROUTINE_DAYS.flatMap(
  (day) => day.exercises
);

export const getExerciseById = (id: string): ExerciseDefinition | undefined =>
  ALL_EXERCISES.find((ex) => ex.id === id);

export const getDayById = (id: string): RoutineDay =>
  ROUTINE_DAYS.find((d) => d.id === id) ?? ROUTINE_DAYS[0];
